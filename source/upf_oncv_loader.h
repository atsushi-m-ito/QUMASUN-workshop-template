class SimpleXMLPerser {
private:
    FILE* m_fp=nullptr;

    struct Tag {
        bool is_text = false;
        std::string name;
        std::vector<Tag*> children;
        std::map<std::string, std::string > property;
    };

    static constexpr int SIZE_ROW = 1024;
    char line[SIZE_ROW];
    //int m_pos = -1;
    Tag top_tags;
public:
    ~SimpleXMLPerser() {
        if (m_fp) Close();

        DeleteChildren(top_tags);
    }



    bool Open(const char* filepath) {
        m_fp = fopen(filepath, "r");
        return (m_fp != nullptr);
    }

    void Close() {
        fclose(m_fp);        
    }

    
    void DeleteChildren(Tag& parent) {
        for (auto&& a : parent.children) {
            DeleteChildren(*a);
            delete a;
        }        
    }

    bool IsAlphabet(char x) {
        if (('a' <= x) && (x <= 'z')) return true;
        if (('A' <= x) && (x <= 'Z')) return true;
        if ('-' == x) return true;
        if ('_' == x) return true;
        return false;
    }
    
    bool IsNumber(char x) {
        if (('0' <= x) && (x <= '9')) return true;
        if ('.' == x) return true;
        return false;
    }

    char* NextNotAlphabetNumber(char* offset) {
        for (char* i = offset; (*i) != '\0'; ++i) {
            if(IsAlphabet(*i)) continue;
            if (IsNumber(*i)) continue;            
            return i;
        }
        return nullptr;
    }


    char* NextMeaning(char* offset) {
        constexpr char DELIMITER[] = " \t\r\n";
        constexpr int LENGTH = 4;
        for (char* i = offset; (*i) != '\0'; ++i) {
            int k;
            for (k = 0; k < LENGTH; ++k) {
                if ((*i) == DELIMITER[k]) break;
            }            
            if (k == LENGTH) return i;
        }
        return nullptr;
    }


    char* NextChar(char* offset, int c) {
        for (char* i = offset; (*i) != '\0'; ++i) {
            if ((*i) == c) return i;
        }
        return nullptr;
    }

    char* NextMeaningHelper(char* offset) {
        char* pos = NextMeaning(offset);
        while (pos ==nullptr ) {
            if (fgets(line, SIZE_ROW, m_fp) == nullptr) {
                break;
            }
            pos = NextMeaning(line);
        }
        return pos;
    }


    char* NextCharHelper(char* offset, int c) {
        char* pos = NextChar(offset, c);
        while (pos == nullptr) {
            if (fgets(line, SIZE_ROW, m_fp) == nullptr) {
                break;
            }
            pos = NextChar(0, c);
        }
        return pos;
    }

    void Perse() {
        if (fgets(line, SIZE_ROW, m_fp) == nullptr) {
            return;
        }
        //top_tags = new Tag;
        LoadChildren(&top_tags, line);
        
    }

    char* LoadChildren(Tag* parent, char* pstart) {
        //内部タグの読み込み//
        char* pos = NextMeaningHelper(pstart);
        char* pend;
        while (pos) {
            if (*pos == '<') {
                if (*(pos + 1) == '/') {
                    pend = NextChar(pos + 2, '>');
                    return pend + 1;
                }else if (*(pos + 1) == '!') {
                    //comment
                    pend = NextCharHelper(pos + 4, '>');
                    while (pend) {
                        if ((*(pend - 1) == '-') && (*(pend - 2) == '-')) {
                            //コメントタグの終端//
                            break;
                        }
                        pend = NextCharHelper(pend + 1, '>');
                    }
                    if (pend == nullptr) {
                        //コメント終端されていない//
                        return nullptr;
                    }
                    pend++;

                } else {
                    Tag* ch_tag;
                    pend = LoadTag(pos, &ch_tag);
                    parent->children.push_back(ch_tag);
                }
            } else {
                //text
                Tag* ch_tag = new Tag;
                ch_tag->is_text = true;
                pend = NextChar(pos, '<');
                while (pend == nullptr) {
                    ch_tag->name += pos;

                    if (fgets(line, SIZE_ROW, m_fp) == nullptr) {
                        break;
                    }
                    pos = line;
                    pend = NextChar(pos, '<');
                }

                parent->children.push_back(ch_tag);
                if (pend == nullptr) {//file終端//
                    return nullptr;
                }

            }
            pos = NextMeaningHelper(pend);
        }
        return nullptr;
    }

    char* LoadTag(char* offset, Tag** ptag) {
                
        char* pos = NextMeaningHelper(offset);
        if (pos == nullptr) return nullptr;

        if (*pos != '<') {
            return nullptr;//error
        }
        //tag start//////////////////////////
        char* pend = NextNotAlphabetNumber(pos+1);
        Tag* tag = new Tag;
        *ptag = tag;
        tag->name = std::string(pos + 1).substr(0, pend - pos-1);
                

        pos = NextMeaningHelper(pend);
        while (pos) {
                
            if (*pos == '/') {
                if (*(pos + 1) == '>') {
                    return pos + 2;//tag終了//
                }
            }else if (*pos == '>') {
                //開始タグだった//
                //内部の読み込み//
                pend = pos + 1;
                break;
            }


            //property list//
            pend = NextNotAlphabetNumber(pos);
            std::string prop_name = std::string(pos).substr(0, pend - pos);

            pos = NextMeaningHelper(pend);
                    
            if (*pos == '=') {
                std::string prop_value;

                //valueがあるので読み込み//
                pos = NextMeaningHelper(pos + 1);
                if (*pos == '\"') {
                    pend = NextCharHelper(pos+1, '\"');
                    prop_value = std::string(pos + 1).substr(0, pend - pos - 1);
                }else{
                    pend = NextNotAlphabetNumber(pos);
                    prop_value = std::string(pos).substr(0, pend - pos);
                }

                tag->property.insert(std::make_pair(prop_name, prop_value));

                pos = NextMeaningHelper(pend + 1);
            } else {

                tag->property.insert(std::make_pair(prop_name, std::string()));

            }
        }

        //内部タグの読み込み//
        pos = LoadChildren(tag, pend);
        return pos;
    }

    //////////////////////////////////
    //検索, 値の取得//////////////////
    //////////////////////////////////
    const std::string GetProperty(const std::vector<std::string>& tag_layer, const std::string& prop_name) {
        Tag* tag = &top_tags;
        for (const auto& t : tag_layer) {
            bool is_found = false;
            for (auto& ch : tag->children) {
                if (ch->name == t) {
                    tag = ch;
                    is_found = true;
                    break;
                }
            }
            if (is_found == false)return std::string();
        }

        auto it = tag->property.find(prop_name);
        if(it == tag->property.end()){
            return std::string();
        }
    
        return it->second;
    }

    const std::string GetText(const std::vector<std::string>& tag_layer) {
        Tag* tag = &top_tags;
        for (const auto& t : tag_layer) {
            bool is_found = false;
            for (auto& ch : tag->children) {
                if (ch->name == t) {
                    tag = ch;
                    is_found = true;
                    break;
                }
            }
            if (is_found == false)return std::string();
        }

        if(tag->children[0]->is_text){
            return tag->children[0]->name;
        }

        return std::string();
    }
};

inline
std::vector<double> ReadDoubleList(const std::string& text, int count) {
    std::vector<double> vals;

    
    const char* p = text.c_str();
    for(int i = 0; i < count; ++i){
        char* endptr;
        double d = std::strtod(p, &endptr);
        /*if (p == endptr) {
            break;
        }
        */
        //数字がもうないときはstrtodが0.0を返すことを利用してvectorを0で埋める//
        vals.push_back(d);
        p = endptr;    
    }
    return vals;
}

