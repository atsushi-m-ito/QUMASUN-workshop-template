        if (count_node == 0) {
            i_inside = (int)((double)i_cutoff * 0.7);
        }else if (count_node == 1) {
            i_cutoff = i_last_inside_node;
            i_inside = (int)((double)i_1st_node * 0.7);
        } else {
            //i_cutoff = i_last_inside_node;
            i_inside = (int)((double)i_1st_node * 1.0);
        }

        //inside 接続点の探索//
